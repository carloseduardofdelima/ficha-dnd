export function getSpellIcon(spell: { id?: string; school?: string; icon?: string }): string {
  const baseId = spell.id?.replace(/-2014$/, '')
  if (baseId && AVAILABLE_SPELL_ICONS.has(baseId)) {
    return `/assets/spells-icons/${baseId}.png`
  }
  const aliasIcon = (spell.id && PT_BR_ICON_ALIASES[spell.id]) || (baseId && PT_BR_ICON_ALIASES[baseId])
  if (aliasIcon && AVAILABLE_SPELL_ICONS.has(aliasIcon)) {
    return `/assets/spells-icons/${aliasIcon}.png`
  }
  if (spell.icon) {
    return `/assets/spells-icons/${spell.icon}`
  }
  if (spell.school && SCHOOL_ICONS[spell.school]) {
    return SCHOOL_ICONS[spell.school]
  }
  return '/assets/spells-icons/arcane-star.png'
}
